// String
let name = "Tawsif";
console.log(name);

// Number
let age = 18;
let price = 99.99;
console.log(age);
console.log(price);

// Boolean
let isStudent = true;
let isGraduated = false;
console.log(isStudent);
console.log(isGraduated);

// Undefined
let result;
console.log(result);

// Null
let selectedUser = null;
console.log(selectedUser);

// BigInt
let bigNumber = 123456789012345678901234567890n;
console.log(bigNumber);

// Symbol
let id = Symbol("id");
console.log(id);

// Object
let user = {
    name: "Tawsif",
    age: 18
};

console.log(user);

// JavaScript is dynamically typed
let value = "Hello";
console.log(value);

value = 100;
console.log(value);

value = true;
console.log(value);