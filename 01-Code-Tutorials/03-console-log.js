// Basic console.log()
console.log("Hello, JavaScript!");

// Numbers and expressions
console.log(10);
console.log(10 + 20);
console.log(100 / 5);

// Multiple values
console.log("Name:", "Tawsif");
console.log("Age:", 18);

// Variables
let name = "Tawsif";
let age = 18;

console.log(name);
console.log(age);
console.log("Name:", name, "Age:", age);

// Expressions
console.log(10 + 20);
console.log(5 * 4);
console.log(10 > 5);

// Objects
let user = {
    name: "Tawsif",
    age: 18
};

console.log(user);

// Debugging
let price = 500;
let quantity = 3;
let total = price * quantity;

console.log("Price:", price);
console.log("Quantity:", quantity);
console.log("Total:", total);

// console.log() returns undefined
console.log(console.log("Hello"));
