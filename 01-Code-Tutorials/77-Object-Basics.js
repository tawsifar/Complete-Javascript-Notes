// Creating an object
const user = {
    name: "Tawsif",
    age: 18,
    university: "CUET"
};

console.log(user);

// Accessing properties
console.log(user.name);
console.log(user.age);

// Bracket notation
console.log(user["university"]);

// Adding a property
user.email = "tawsif@example.com";

console.log(user);

// Updating a property
user.age = 19;

console.log(user.age);