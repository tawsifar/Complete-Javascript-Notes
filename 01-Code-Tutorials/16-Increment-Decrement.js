// Increment
let count = 5;

count++;

console.log(count);

// Decrement
count--;

console.log(count);

// Prefix increment
let a = 5;

let result1 = ++a;

console.log(result1);
console.log(a);

// Postfix increment
let b = 5;

let result2 = b++;

console.log(result2);
console.log(b);

// Prefix decrement
let c = 5;

let result3 = --c;

console.log(result3);
console.log(c);

// Postfix decrement
let d = 5;

let result4 = d--;

console.log(result4);
console.log(d);

// Increment in a loop
for (let i = 0; i < 5; i++) {
    console.log(i);
}