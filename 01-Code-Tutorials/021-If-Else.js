// Basic if...else
let age = 20;

if (age >= 18) {
    console.log("Adult");
} else {
    console.log("Minor");
}

// Login example
let isLoggedIn = false;

if (isLoggedIn) {
    console.log("Welcome!");
} else {
    console.log("Please log in.");
}

// Even or odd
let number = 7;

if (number % 2 === 0) {
    console.log("Even");
} else {
    console.log("Odd");
}

// Comparing values
let password = "12345";

if (password === "12345") {
    console.log("Access granted");
} else {
    console.log("Access denied");
}
