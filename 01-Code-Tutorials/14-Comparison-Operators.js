// Equal
console.log(5 == 5);
console.log(5 == "5");

// Strictly equal
console.log(5 === 5);
console.log(5 === "5");

// Not equal
console.log(5 != 10);
console.log(5 != "5");

// Strictly not equal
console.log(5 !== 10);
console.log(5 !== "5");

// Greater than
console.log(10 > 5);

// Less than
console.log(5 < 10);

// Greater than or equal
console.log(10 >= 10);
console.log(10 >= 5);

// Less than or equal
console.log(5 <= 5);
console.log(5 <= 10);

