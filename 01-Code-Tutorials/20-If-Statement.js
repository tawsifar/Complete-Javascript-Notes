// Basic if statement
let age = 20;

if (age >= 18) {
    console.log("Adult");
}

// Boolean condition
let isLoggedIn = true;

if (isLoggedIn) {
    console.log("Welcome!");
}

// Multiple conditions
let userAge = 20;
let hasID = true;

if (userAge >= 18 && hasID) {
    console.log("Entry allowed");
}

// Comparison in if
let score = 85;

if (score >= 80) {
    console.log("Excellent");
}

// Truthy and falsy values
let username = "";

if (username) {
    console.log("Username exists");
}
