// Creating an array
const fruits = ["Apple", "Banana", "Mango"];

console.log(fruits);

// Accessing elements
console.log(fruits[0]);
console.log(fruits[1]);

// Updating an element
fruits[1] = "Orange";

console.log(fruits);

// Array length
console.log(fruits.length);

// Arrays can store different value types
const values = ["Tawsif", 18, true, null];

console.log(values);

// Empty array
const numbers = [];

numbers[0] = 10;
numbers[1] = 20;

console.log(numbers);
