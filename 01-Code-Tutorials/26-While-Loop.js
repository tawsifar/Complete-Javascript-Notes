// Basic while loop
let i = 1;

while (i <= 5) {
    console.log(i);
    i++;
}

// Countdown
let count = 5;

while (count >= 1) {
    console.log(count);
    count--;
}

// Condition-based loop
let attempts = 0;

while (attempts < 3) {
    console.log("Checking...");
    attempts++;
}

// Avoid infinite loops by updating the condition
let number = 1;

while (number <= 3) {
    console.log(number);
    number++;
}
