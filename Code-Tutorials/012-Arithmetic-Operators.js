// Addition
let a = 10;
let b = 5;

console.log(a + b);

// Subtraction
console.log(10 - 5);

// Multiplication
console.log(10 * 5);

// Division
console.log(10 / 5);
console.log(5 / 2);

// Remainder
console.log(10 % 3);

// Even and odd check
let number = 10;

console.log(number % 2);

// Exponentiation
console.log(2 ** 3);

// Operator precedence
console.log(10 + 5 * 2);

// Parentheses change the order
console.log((10 + 5) * 2);

// Unary plus converts a numeric string
let value = "100";

console.log(+value);