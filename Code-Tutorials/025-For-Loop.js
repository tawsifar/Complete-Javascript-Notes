// Basic for loop
for (let i = 1; i <= 5; i++) {
    console.log(i);
}

// Counting backward
for (let i = 5; i >= 1; i--) {
    console.log(i);
}

// Even numbers
for (let i = 2; i <= 10; i += 2) {
    console.log(i);
}

// Loop through a string
let name = "Tawsif";

for (let i = 0; i < name.length; i++) {
    console.log(name[i]);
}
