// Basic assignment
let score = 100;

console.log(score);

// Addition assignment
score += 20;

console.log(score);

// Subtraction assignment
score -= 10;

console.log(score);

// Multiplication assignment
score *= 2;

console.log(score);

// Division assignment
score /= 2;

console.log(score);

// Remainder assignment
let number = 10;

number %= 3;

console.log(number);

// Exponentiation assignment
let power = 2;

power **= 3;

console.log(power);

